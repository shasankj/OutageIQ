-- 0002_rag_schema.sql: vector store for knowledge chunks (schema rag, pgvector 0.8.x).
-- One row per (strategy, content, model, dimensions): the content hash makes re-indexing
-- unchanged chunks free (embedding cache). vector(1024) matches Titan V2's default size;
-- experiments with 256/512 dims use their own tables.

CREATE TABLE rag.chunks (
  chunk_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  strategy       text NOT NULL,
  source         text NOT NULL,
  section        text NOT NULL,
  doc_type       text NOT NULL,
  tables         text[] NOT NULL DEFAULT '{}',
  schema_version integer NOT NULL,
  content        text NOT NULL,
  content_hash   text NOT NULL,
  embed_model    text NOT NULL,
  dims           integer NOT NULL,
  embedding      vector(1024) NOT NULL,
  content_tsv    tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (strategy, content_hash, embed_model, dims)
);
COMMENT ON TABLE rag.chunks IS 'Embedded knowledge chunks. Search with cosine distance (embedding <=> query) or full text (content_tsv).';

CREATE INDEX chunks_embedding_hnsw ON rag.chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX chunks_content_tsv ON rag.chunks USING gin (content_tsv);
CREATE INDEX chunks_doc_type ON rag.chunks (doc_type);
