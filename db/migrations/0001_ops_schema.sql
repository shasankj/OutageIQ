-- 0001_ops_schema.sql: operational tables for OutageIQ (all synthetic data).
-- Conventions: see docs/adr/0004. PKs are <entity>_id; every table has created_at,
-- updated_at, created_by; all timestamps are timestamptz (docs/adr/0003).
-- Exception on purpose: tickets.created_at / updated_at are BUSINESS times (when the ticket
-- was opened / last changed), set explicitly by loaders; see their column comments.

CREATE OR REPLACE FUNCTION ops.set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- ---------------------------------------------------------------- sites
CREATE TABLE ops.sites (
  site_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_code   text NOT NULL UNIQUE,
  site_name   text NOT NULL,
  region      text NOT NULL,
  state       char(2) NOT NULL,
  city        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  created_by  text NOT NULL DEFAULT current_user
);
COMMENT ON TABLE  ops.sites IS 'Cell sites (physical network locations). One row per site.';
COMMENT ON COLUMN ops.sites.site_id   IS 'Surrogate primary key. Join key for outages.site_id.';
COMMENT ON COLUMN ops.sites.site_code IS 'Business identifier shown to users, e.g. NJ-EDISON-042. Unique.';
COMMENT ON COLUMN ops.sites.region    IS 'Operations region, e.g. NJ-Central.';
COMMENT ON COLUMN ops.sites.state     IS 'Two-letter US state code.';

-- ---------------------------------------------------------------- users
CREATE TABLE ops.users (
  user_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   text NOT NULL,
  email       text NOT NULL UNIQUE,
  team        text NOT NULL,
  region      text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  created_by  text NOT NULL DEFAULT current_user
);
COMMENT ON TABLE  ops.users IS 'Employees who work tickets (synthetic people). One row per person.';
COMMENT ON COLUMN ops.users.user_id   IS 'Surrogate primary key. Join key for tickets.assigned_user_id.';
COMMENT ON COLUMN ops.users.full_name IS 'Person''s display name. Use this, not user_id, when a question names a person.';
COMMENT ON COLUMN ops.users.team      IS 'Team name, e.g. Field Ops.';

-- ---------------------------------------------------------------- root_causes
CREATE TABLE ops.root_causes (
  root_cause_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category      text NOT NULL,
  subcategory   text NOT NULL,
  description   text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  created_by    text NOT NULL DEFAULT current_user,
  UNIQUE (category, subcategory)
);
COMMENT ON TABLE  ops.root_causes IS 'Catalog of root causes. An outage links to one or more via outage_root_causes.';
COMMENT ON COLUMN ops.root_causes.category    IS 'Top-level group, e.g. Transport, Power, Software.';
COMMENT ON COLUMN ops.root_causes.subcategory IS 'Finer group, e.g. Physical (fiber cut).';

-- ---------------------------------------------------------------- outages
CREATE TABLE ops.outages (
  outage_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id      bigint NOT NULL REFERENCES ops.sites (site_id),
  outage_type  text NOT NULL CHECK (outage_type IN ('OOS', 'SC', 'TIS', 'MO')),
  network_domain text NOT NULL CHECK (network_domain IN ('RAN', 'Core', 'Transport')),
  priority     text NOT NULL CHECK (priority IN ('low', 'medium', 'high', 'critical')),
  start_time   timestamptz NOT NULL,
  end_time     timestamptz,
  is_open      boolean GENERATED ALWAYS AS (end_time IS NULL) STORED,
  cells_affected integer NOT NULL DEFAULT 0 CHECK (cells_affected >= 0),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  created_by   text NOT NULL DEFAULT current_user,
  CHECK (end_time IS NULL OR end_time >= start_time)
);
COMMENT ON TABLE  ops.outages IS 'Network outages. One row per outage. Central table: tickets, alarms, updates, root causes and impacted services all reference outage_id.';
COMMENT ON COLUMN ops.outages.outage_id   IS 'Primary key. "Outage 1234" in a question means outage_id = 1234.';
COMMENT ON COLUMN ops.outages.outage_type IS 'OOS = Out of Service, SC = Sleepy Cell, TIS = Top Impaired Site, MO = Micro Outage.';
COMMENT ON COLUMN ops.outages.network_domain IS 'Network layer: RAN, Core or Transport.';
COMMENT ON COLUMN ops.outages.priority    IS 'low, medium, high or critical (lowercase). Independent of tickets.priority, which can be escalated later.';
COMMENT ON COLUMN ops.outages.start_time  IS 'When the outage began (UTC timestamptz). Never NULL.';
COMMENT ON COLUMN ops.outages.end_time    IS 'When service was restored. NULL means the outage is still open/ongoing; do not compute a duration from it.';
COMMENT ON COLUMN ops.outages.is_open     IS 'Generated: true when end_time IS NULL.';
COMMENT ON COLUMN ops.outages.cells_affected IS 'Number of cells impacted.';

-- ---------------------------------------------------------------- outage_root_causes
CREATE TABLE ops.outage_root_causes (
  outage_id     bigint NOT NULL REFERENCES ops.outages (outage_id),
  root_cause_id bigint NOT NULL REFERENCES ops.root_causes (root_cause_id),
  is_primary    boolean NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  created_by    text NOT NULL DEFAULT current_user,
  PRIMARY KEY (outage_id, root_cause_id)
);
CREATE UNIQUE INDEX one_primary_root_cause_per_outage
  ON ops.outage_root_causes (outage_id) WHERE is_primary;
COMMENT ON TABLE  ops.outage_root_causes IS 'Links outages to root causes (many-to-many). An ongoing outage may have none yet.';
COMMENT ON COLUMN ops.outage_root_causes.is_primary IS 'True for the main cause; at most one per outage.';

-- ---------------------------------------------------------------- alarms
CREATE TABLE ops.alarms (
  alarm_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outage_id   bigint NOT NULL REFERENCES ops.outages (outage_id),
  site_id     bigint NOT NULL REFERENCES ops.sites (site_id),
  alarm_code  text NOT NULL,
  severity    text NOT NULL CHECK (severity IN ('warning', 'minor', 'major', 'critical')),
  description text NOT NULL,
  raised_at   timestamptz NOT NULL,
  cleared_at  timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  created_by  text NOT NULL DEFAULT current_user,
  CHECK (cleared_at IS NULL OR cleared_at >= raised_at)
);
COMMENT ON TABLE  ops.alarms IS 'Equipment alarms raised during an outage. Many alarms per outage.';
COMMENT ON COLUMN ops.alarms.severity   IS 'Alarm severity: warning, minor, major, critical. Not the same scale as outage priority.';
COMMENT ON COLUMN ops.alarms.raised_at  IS 'When the alarm fired.';
COMMENT ON COLUMN ops.alarms.cleared_at IS 'When it cleared. NULL means still active.';

-- ---------------------------------------------------------------- outage_updates
CREATE TABLE ops.outage_updates (
  outage_update_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outage_id        bigint NOT NULL REFERENCES ops.outages (outage_id),
  posted_by_user_id bigint REFERENCES ops.users (user_id),
  posted_at        timestamptz NOT NULL,
  update_text      text NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  created_by       text NOT NULL DEFAULT current_user
);
COMMENT ON TABLE  ops.outage_updates IS 'Timeline of status notes on an outage. Latest update = max(posted_at).';
COMMENT ON COLUMN ops.outage_updates.posted_at IS 'When the note was written (business time).';

-- ---------------------------------------------------------------- tickets
CREATE TABLE ops.tickets (
  ticket_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_number    text NOT NULL UNIQUE CHECK (ticket_number ~ '^INC-[0-9]+$'),
  outage_id        bigint NOT NULL REFERENCES ops.outages (outage_id),
  status           text NOT NULL CHECK (status IN ('open', 'in_progress', 'resolved', 'closed')),
  priority         text NOT NULL CHECK (priority IN ('low', 'medium', 'high', 'critical')),
  assigned_user_id bigint REFERENCES ops.users (user_id),
  created_at       timestamptz NOT NULL,
  updated_at       timestamptz NOT NULL,
  resolved_at      timestamptz,
  is_resolved      boolean GENERATED ALWAYS AS (resolved_at IS NOT NULL) STORED,
  created_by       text NOT NULL DEFAULT current_user,
  CHECK (resolved_at IS NULL OR resolved_at >= created_at),
  CHECK ((status IN ('resolved', 'closed')) = (resolved_at IS NOT NULL))
);
COMMENT ON TABLE  ops.tickets IS 'Incident tickets. An outage can have zero, one or several tickets; an outage with no ticket has no row here (use LEFT JOIN from outages).';
COMMENT ON COLUMN ops.tickets.ticket_id     IS 'Surrogate primary key (internal). Not what users mean by "ticket INC-55821".';
COMMENT ON COLUMN ops.tickets.ticket_number IS 'Business identifier shown to users, e.g. INC-55821. Unique.';
COMMENT ON COLUMN ops.tickets.status        IS 'open, in_progress, resolved or closed. resolved/closed exactly when resolved_at is set.';
COMMENT ON COLUMN ops.tickets.priority      IS 'low, medium, high or critical (lowercase). May differ from outages.priority if escalated.';
COMMENT ON COLUMN ops.tickets.assigned_user_id IS 'Current assignee (users.user_id). NULL = unassigned. History is in ticket_assignments.';
COMMENT ON COLUMN ops.tickets.created_at    IS 'BUSINESS time the ticket was opened (not row insert time).';
COMMENT ON COLUMN ops.tickets.updated_at    IS 'BUSINESS time of the last ticket change.';
COMMENT ON COLUMN ops.tickets.resolved_at   IS 'When the ticket was resolved. NULL = not resolved yet.';
COMMENT ON COLUMN ops.tickets.is_resolved   IS 'Generated: true when resolved_at IS NOT NULL.';

-- ---------------------------------------------------------------- ticket_assignments
CREATE TABLE ops.ticket_assignments (
  ticket_assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id     bigint NOT NULL REFERENCES ops.tickets (ticket_id),
  user_id       bigint NOT NULL REFERENCES ops.users (user_id),
  assigned_at   timestamptz NOT NULL,
  unassigned_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  created_by    text NOT NULL DEFAULT current_user,
  CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);
COMMENT ON TABLE  ops.ticket_assignments IS 'Assignment history. The current assignee row has unassigned_at NULL (and matches tickets.assigned_user_id). More than one row per ticket means it was reassigned.';

-- ---------------------------------------------------------------- impacted_services
CREATE TABLE ops.impacted_services (
  impacted_service_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outage_id           bigint NOT NULL REFERENCES ops.outages (outage_id),
  service_name        text NOT NULL,
  customers_impacted  integer NOT NULL CHECK (customers_impacted >= 0),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  created_by          text NOT NULL DEFAULT current_user,
  UNIQUE (outage_id, service_name)
);
COMMENT ON TABLE  ops.impacted_services IS 'Services degraded by an outage with customers affected per service. Total customers for an outage = SUM(customers_impacted) over its rows (a customer may be counted once per service).';

-- ---------------------------------------------------------------- indexes
CREATE INDEX ON ops.outages (site_id);
CREATE INDEX ON ops.outages (start_time);
CREATE INDEX ON ops.alarms (outage_id);
CREATE INDEX ON ops.outage_updates (outage_id, posted_at);
CREATE INDEX ON ops.tickets (outage_id);
CREATE INDEX ON ops.tickets (assigned_user_id);
CREATE INDEX ON ops.ticket_assignments (ticket_id);
CREATE INDEX ON ops.impacted_services (outage_id);

-- ---------------------------------------------------------------- updated_at triggers
-- tickets is excluded: its updated_at is a business time set by the loader.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['sites','users','root_causes','outages','outage_root_causes',
                           'alarms','outage_updates','ticket_assignments','impacted_services']
  LOOP
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON ops.%1$s
                    FOR EACH ROW EXECUTE FUNCTION ops.set_updated_at()', t);
  END LOOP;
END $$;
